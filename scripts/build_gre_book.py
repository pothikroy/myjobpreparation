"""Rebuild GRE section/page/answer metadata from the user-supplied scan.

Usage: python scripts/build_gre_book.py --pdf book.pdf --text extracted-layout.txt
Requires pdfplumber. Generate the text with pdftotext -layout. No OCR question
text or formulas are rewritten into questions; the reader displays the source.
"""
import argparse
import hashlib
import json
import re
from pathlib import Path
import pdfplumber

parser = argparse.ArgumentParser()
parser.add_argument('--pdf', required=True, type=Path)
parser.add_argument('--text', required=True, type=Path)
args = parser.parse_args()
pages = args.text.read_text(encoding='utf-8').split('\f')
if not pages[-1].strip(): pages.pop()
keys = [(i+1, int(re.search(r'FOR GENERAL TEST\s*(\d+)', t, re.I)[1]))
        for i,t in enumerate(pages) if re.search(r'FOR GENERAL TEST\s*\d', t, re.I) and 'Answer Key' in t[:500]]
assert len(pages) == 1089 and [n for _,n in keys] == list(range(1,28))
tests = []
with pdfplumber.open(args.pdf) as pdf:
    for index,(key_page,number) in enumerate(keys):
        start = 31 if index == 0 else keys[index-1][0]+2
        sections = []
        for page in range(start,key_page):
            head = pages[page-1][:650]
            match = re.search(r'SEC[Tf]ION\s*([1-7I!])(?!\w)',head,re.I)
            if not match: continue
            count = re.search(r'([0-9D]+)\s+Que',head,re.I)
            assert count, (number,page,'missing question count')
            count = int(count[1].replace('D','0'))
            kind = {25:'analytical',30:'quantitative',37:'verbal',38:'verbal'}[count]
            section_number = int(match[1]) if match[1].isdigit() else 1
            sections.append({'id':f't{number:02}-s{section_number}','test':number,'number':section_number,'kind':kind,'startPage':page,'headerCount':count,'minutes':30})
        assert len(sections)==6 and len({s['number'] for s in sections})==6,(number,sections)
        for i,section in enumerate(sections): section['endPage'] = sections[i+1]['startPage']-1 if i<5 else key_page-1
        words = pdf.pages[key_page-1].extract_words(x_tolerance=1.5,y_tolerance=2)
        labels = sorted([w for w in words if re.match(r'^[NH]um',w['text'],re.I) and w['top']<190],key=lambda w:w['x0'])
        assert len(labels)==6,(number,'table column labels')
        foot = min([w['top'] for w in words if 'Estimated' in w['text']]+[640])
        columns=[]
        for col,label in enumerate(labels):
            center=label['x0']+41.5
            cells=sorted([w for w in words if abs((w['x0']+w['x1'])/2-center)<9 and label['bottom']+1<w['top']<foot-4],key=lambda w:w['top'])
            values=[re.sub('[^A-Za-z0-9]','',w['text']).upper() for w in cells]
            values=[v for v in values if v]
            # Visually checked against the original key pages; see SOURCE.md.
            if number==24 and col==1: values.remove('I')
            if number==23 and col==2: values.insert(21,'D')
            if number==6 and col==0: values[13]='D'
            if number==10 and col==0: values[2]='C'
            if number==21 and col==1: values[1]='C'
            values=[{'0':'D','O':'D','8':'B'}.get(v,v) for v in values]
            assert all(v in 'ABCDE' and len(v)==1 for v in values),(number,col,values)
            columns.append(''.join(values))
        ordered=[s for kind in ['verbal','quantitative','analytical'] for s in sections if s['kind']==kind]
        for section,answers in zip(ordered,columns):
            expected = 37 if (number,section['number']) in [(3,3),(21,6)] else {'verbal':38,'quantitative':30,'analytical':25}[section['kind']]
            assert len(answers)==expected,(number,section['number'],len(answers),expected)
            section['answers']=answers;section['count']=expected;section['keyPage']=key_page
            if section['headerCount']!=expected:section['sourceNote']='The heading says 38, but this scan and its answer key contain questions 1–37.'
            section.pop('headerCount')
        tests.append({'number':number,'startPage':start,'endPage':key_page-1,'keyPage':key_page,'sections':sections})
book={'title':'GRE Big Book','edition':'ETS, 1996','pageCount':len(pages),'sha256':hashlib.sha256(args.pdf.read_bytes()).hexdigest(),'tests':tests,'questionCount':sum(s['count'] for t in tests for s in t['sections'])}
assert book['questionCount']==5020
target=Path(__file__).resolve().parents[1]/'bank/gre-big-book/book-data.js'
target.parent.mkdir(parents=True,exist_ok=True)
target.write_text('/* Generated by scripts/build_gre_book.py; see SOURCE.md. */\nwindow.GRE_BOOK = '+json.dumps(book,ensure_ascii=False,separators=(',',':'))+';\n',encoding='utf-8')
print(f"Indexed {len(tests)} tests, 162 sections, {book['questionCount']} answer-key entries.")
